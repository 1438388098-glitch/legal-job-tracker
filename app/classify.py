import re

CITIES = ["广州", "深圳", "珠海", "佛山", "惠州", "东莞", "中山", "江门", "肇庆",
          "韶关", "汕头", "湛江", "茂名", "清远", "梅州", "河源", "阳江", "云浮",
          "潮州", "揭阳", "汕尾"]

# 顺序即优先级：越具体的身份越靠前。
# 曾经只有"法院|事业单位|律师事务所|法务"这几个词，导致人社厅栏目里
# "广州中医药大学第三附属医院2026年公开招聘工作人员公告"这类（正文里没有任何
# 命中词）全部落进"未分类"，实测占比 47%。
_RULES = [
    ("intern", re.compile(r"实习|见习")),
    ("lawfirm", re.compile(
        r"律师事务所|律所|执业律师|授薪律师|合伙人|律师助理|法律事务所")),
    ("legal_counsel", re.compile(
        r"法务|合规|法律顾问|企业法律|法律事务|风控|知识产权|专利|商标|"
        r"合同管理|法规")),
    ("public", re.compile(
        r"法院|检察院|公务员|事业单位|书记员|法官助理|检察官助理|招录|"
        r"警务辅助|审判辅助|检察辅助|司法辅助|国资|国企|编制|雇员|"
        r"政府购买|公益性岗位|选调生|选调|三支一扶|社区工作者|社会工作者|"
        r"公开招聘|公开选聘|公开招考|公开遴选|集中招聘|统一招聘|人才引进|"
        r"急需人才|高层次人才|紧缺人才|辅导员|教职工|教师|医师|护士|"
        r"工作人员|专技|管理岗|工勤|聘员|"
        r"大学|学院|学校|中学|小学|幼儿园|医院|疾病预防|妇幼|"
        r"管委会|管理委员会|人民政府|公证处|仲裁委|法律援助|司法所|"
        r"公安|消防|税务|海关|海事|监狱|戒毒|街道办事处|镇政府")),
]


def infer_job_type(text: str) -> str:
    for key, pat in _RULES:
        if pat.search(text or ""):
            return key
    return "unknown"


def infer_city(text: str, default: str | None = None):
    for c in CITIES:
        if c in (text or ""):
            return c
    return default


# ── 用工性质 ────────────────────────────────────────────────────────────
# 法学求职者第一关心的是"有没有编制"，其次是"是不是长期有效岗"。
# 这两类信息正文里几乎一定写了，但此前没有结构化成字段，导致搜不了、筛不了。
EMP_BIANZHI = "编制"
EMP_CONTRACT = "合同制"
EMP_DISPATCH = "派遣"
EMP_ROLLING = "长期有效"

_EMP_RULES = [
    (EMP_DISPATCH, re.compile(
        r"劳务派遣|派遣用工|劳动派遣|人才派遣|外包")),
    (EMP_BIANZHI, re.compile(
        r"事业编制|在编|入编|解决编制|带编制|编制内|公务员(编制|身份)?|"
        r"纳入编制|实名编制|员额制|备案制管理")),
    (EMP_CONTRACT, re.compile(
        r"劳动合同制|聘用制|合同制|编外|政府购买服务|聘员|劳动合同聘用|"
        r"签订劳动合同|非在编")),
]

# "长期有效/招满即止/邮箱投递"：这类岗位没有（也不需要）截止日期，
# 之前因为没有 deadline 被排到列表最底部，等于永远看不到。
_ROLLING = re.compile(
    r"长期(有效|招聘|招录)|招满即止|常年招聘|滚动招聘|"
    r"简历(发送|投递).{0,12}(邮箱|邮件)|邮箱.{0,8}(投递|报名)|"
    r"招聘(信息)?长期有效|不设截止|roll")


def infer_employment_type(text: str) -> str | None:
    t = text or ""
    for key, pat in _EMP_RULES:
        if pat.search(t):
            return key
    return None


def is_rolling(text: str) -> bool:
    return bool(_ROLLING.search(text or ""))


# ── 单位名抽取 ──────────────────────────────────────────────────────────
# 政务站的列表页只有"标题 + 日期"，没有单位字段，但单位名几乎都在标题开头：
#   "广东省高级人民法院2026年度选调优秀大学毕业生拟录用人员名单公示" → 广东省高级人民法院
#   "广州中医药大学第三附属医院2026年第一批公开招聘工作人员公告"     → 广州中医药大学第三附属医院
#   "广东检察官（培训）学院集中公开招聘面试公告"                     → 广东检察官（培训）学院
# 做法：以"机构后缀词"为锚点，向后确认紧跟的确实是正文（年份/招聘类词），
# 取最长的那一段。抽不到就返回 None —— 宁可空着，也不要显示半句话当单位。

# 机构后缀词：候选单位名必须以其中一个结尾。
# 刻意不放"所"这类单字——"广东省人社厅所属事业单位招聘公告"会被切成"…厅所"。
_ORG_TAIL = re.compile(
    r"人民法院|人民检察院|高级法院|中级法院|法院|检察院|"
    r"大学|学院|学校|中学|小学|幼儿园|职业技术学院|技师学院|"
    r"律师事务所|律所|公证处|仲裁委员会|仲裁委|法律援助中心|"
    r"管理委员会|管委会|委员会|人民政府|街道办事处|镇政府|"
    r"直属事业单位|下属事业单位|所属事业单位|事业单位|"
    r"研究院|研究所|科学院|设计院|检测院|勘察院|"
    r"协会|学会|联合会|工会|基金会|红十字会|"
    r"医院|妇幼保健院|疾病预防控制中心|卫生院|社区卫生服务中心|"
    r"有限公司|股份有限公司|集团|公司|银行|证券|保险|事务所|"
    r"中心|基地|总站|工作站|服务站|"
    r"管理局|监督局|保障局|资源局|建设局|税务局|市场监督管理局|"
    r"厅|局|部|委|署|办|处|站|馆|台|社|队|校|厂")

# 分界词：出现即说明"单位名已说完，后面是正文"
_ORG_CUT = re.compile(
    r"关于|公开|招聘|招录|招考|选聘|选调|引进|招募|诚聘|集中|统一|面向|"
    r"拟聘|拟录|录用|公示|公告|通知|简章|启事|方案|办法|细则|规定|说明|"
    r"人员|名单|成绩|面试|笔试|体检|考察|资格|报名|考试|录取|聘用|"
    r"20\d{2}\s*年|年度|第[一二三四五六七八九十百\d]+(?:批|次|期|轮|阶段)|"
    r"[（(【\[]|[:：｜|]|·|\s")

# 正文词：候选单位名里出现任何一个，说明抽多了（已跨过正文又撞上另一个机构后缀）
_ORG_CUT_STRONG = re.compile(
    r"关于|公开招聘|招聘|招录|招考|选聘|选调|引进|招募|诚聘|拟聘|拟录|录用|"
    r"聘用|公示|公告|通知|简章|启事|人员|名单|面试|笔试|体检|考察|报名|考试|"
    r"劳动合同|书记员|雇员|岗位|派遣|[｜|]")

# 标题开头的"时间前缀"，先剥掉再找单位（"2025年度广东检察官（培训）学院…"）
_ORG_LEAD = re.compile(
    r"^(?:20\d{2}\s*年(?:度|第[一二三四五六七八九十\d]+批)?|"
    r"第[一二三四五六七八九十\d]+批|[\d]{1,2}月|【[^】]*】|\[[^\]]*\])+")

_ORG_TRIM = " -–—、,，。.·|｜:：;；"


def extract_org(title: str) -> str | None:
    """从公告标题里抽取单位名。抽不到返回 None（宁缺勿错）。

    以机构后缀词为锚点枚举候选：要求锚点右边确实紧接着正文（年份、招聘类词，
    或干脆是标题结尾），且候选本身不含正文词；在合格候选里取最长的那个。
    """
    t = " ".join((title or "").split())
    if len(t) < 4:
        return None
    t = _ORG_LEAD.sub("", t).strip()
    if len(t) < 4:
        return None

    best = None
    for m in _ORG_TAIL.finditer(t):
        end = m.end()
        cand = t[:end].strip(_ORG_TRIM)
        if not (4 <= len(cand) <= 40):
            continue
        if _ORG_CUT_STRONG.search(cand):
            continue  # "…人民法院关于转发…人民法院" 这类跨过了正文
        rest = t[end:]
        ok = (not rest
              or bool(_ORG_CUT.match(rest))
              or (len(rest) <= 14 and bool(_ORG_CUT_STRONG.search(rest))))
        if ok and (best is None or len(cand) > len(best)):
            best = cand
    return best


# ── 公告性质 ────────────────────────────────────────────────────────────
# 政务渠道里很大一部分稿件不是"开放报名的岗位"，而是事后结果公示
# （拟聘用人员名单公示 / 笔试成绩公告 / 体检考察公告）。实测某批 299 条里
# 这类占近半，且天然没有投递截止日——混在列表里就是用户说的"乱七八糟"。
# 分类后默认隐藏结果类，但保留可搜索（想查"我那次考试结果"时还能找到）。
NOTICE_OPENING = "opening"   # 可投递：招聘公告 / 招考 / 选聘 / 引进
NOTICE_RESULT = "result"     # 事后结果：拟聘公示 / 成绩 / 分数线 / 体检 / 考察
NOTICE_INFO = "info"         # 其他信息类：系统升级、论文征集、办事指南等

_RESULT = re.compile(
    r"拟聘用|拟录用|拟聘人员|聘用人员名单|录用人员名单|拟聘用人选|"
    r"人选名单|名单公示|有关人选|"
    r"成绩(公告|查询|公布|排名)|合格分数线|笔试合格|面试成绩|总成绩|"
    r"体检(公告|通知|结果)|考察(公告|对象)|拟任|任前公示|公示名单|"
    r"人员名单公示|资格审核(公告|结果)|拟确定|招聘结果|入围|递补")
# 采购/招标类稿件常带"招聘活动"字样但是给供应商看的（如招聘会项目询价），对求职者无用
_NON_JOB = re.compile(
    r"询价|招标|中标|成交(公告|结果)|采购(公告|项目|意向)|比选|竞谈|"
    r"征求意见|意见征集|论文征集|征文|问卷|调查|听证会")
_OPENING = re.compile(
    r"招聘|招录|招考|选聘|选调|引进|招募|诚聘|广纳英才|招贤|岗位(表|信息)|公开招聘|公开遴选")


def infer_notice_kind(title: str, body: str = "") -> str:
    """判断稿件性质。标题优先——标题里出现"公示/成绩"基本就是结果类，
    即便正文提到"招聘"（"根据《…公开招聘公告》规定"）也不该当成开放岗位。"""
    t = title or ""
    if _RESULT.search(t):
        return NOTICE_RESULT
    if _NON_JOB.search(t):
        return NOTICE_INFO
    if _OPENING.search(t):
        return NOTICE_OPENING
    # 标题看不出性质时看正文前半段（正文常常大段复述历史流程，只看开头更准）
    head = (body or "")[:600]
    if _RESULT.search(head):
        return NOTICE_RESULT
    if _OPENING.search(head):
        return NOTICE_OPENING
    return NOTICE_INFO
